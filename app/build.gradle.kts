android {
    namespace = "com.example.pocketbill"
    compileSdk = 37

    defaultConfig {
        // PLACEHOLDER application ID. Must be replaced before the first Play upload (docs/DECISIONS.md D-002).
        applicationId = "com.example.pocketbill"
        minSdk = 26
        targetSdk = 37
        versionCode = 2
        versionName = "1.0.1"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    // Release signing (P8-T06): the upload key and its passwords live OUTSIDE the repository, in
    // keystore.properties (git-ignored), created by tools/make-upload-key.ps1. Without that file,
    // release builds are simply unsigned; debug builds are unaffected.
    val keystoreFile = rootProject.file("keystore.properties")
    val releaseSigning = if (keystoreFile.exists()) {
        val props = Properties().apply { keystoreFile.inputStream().use { load(it) } }
        signingConfigs.create("release") {
            storeFile = file(props.getProperty("storeFile"))
            storePassword = props.getProperty("storePassword")
            keyAlias = props.getProperty("keyAlias")
            keyPassword = props.getProperty("keyPassword")
        }
    } else {
        null
    }

    buildTypes {
        // A second copy of the app for hands-on testing: installs beside the real one with its own
        // empty data ("PocketBill QA"), so checks never touch the founder's invoices.
        create("qa") {
            initWith(getByName("debug"))
            applicationIdSuffix = ".qa"
            versionNameSuffix = "-qa"
            matchingFallbacks += listOf("debug")
        }
        release {
            signingConfig = releaseSigning
            // R8 stays off for 1.0 (D-022): the app is small, and an untested shrunk build is a
            // bigger risk than a few MB. Turn on only with a full release test on a spare phone.
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }
}

